"""The tree must not expand a node it has no way to split.

`min_samples_leaf` was enforced only when a candidate split was validated, never in the stopping
rule. So a node holding fewer than two leaves' worth of samples was expanded anyway: a full pool
of candidate features was generated and scored, every one was rejected by `_is_split_valid`, and
the node became a leaf regardless.

The resulting tree was the same either way, which is why this stayed invisible offline. On a live
run it was not the same at all -- the pool is generated by API calls, so an unsplittable node cost
real tokens to produce nothing, and then tripped the integrity check for having no usable
language-model feature, whose message points the reader at credentials rather than at arithmetic.
That is how one run lost three of six trees at a depth-3 node of 48 samples under
`min_samples_leaf = 32`.

Offline, LLM-free and deterministic: `CartFeatureFinder` supplies the naive candidate population,
so a whole tree fits without a single model call.
"""

import numpy as np
import pandas as pd

from deft.features.feature_finder import CartFeatureFinder
from deft.trees.split_criterion import GiniCriterion
from deft.trees.tree import AdaptiveDecisionTree


class CountingFinder(CartFeatureFinder):
    """A CART finder that records how often the tree asked it to find a split."""

    def __init__(self):
        super().__init__()
        self.calls = 0

    def get_optimal_feature(self, X, y, **kwargs):
        self.calls += 1
        return super().get_optimal_feature(X, y, **kwargs)


def _data(n_rows: int):
    rng = np.random.default_rng(0)
    X = pd.DataFrame({"a": rng.normal(size=n_rows), "b": rng.normal(size=n_rows)})
    y = np.array([0, 1] * (n_rows // 2))
    return X, y


def _tree(finder, min_samples_leaf, max_depth=3):
    return AdaptiveDecisionTree(
        feature_finder=finder,
        splitting_criterion=GiniCriterion(),
        max_depth=max_depth,
        min_samples_leaf=min_samples_leaf,
        save_locally=False,
    )


def test_a_node_too_small_to_split_is_never_expanded():
    """48 samples cannot be cut into two leaves of 32. No candidate should be asked for."""
    X, y = _data(48)
    finder = CountingFinder()

    tree = _tree(finder, min_samples_leaf=32)
    tree.fit(X, y, sequence_column=None)

    assert finder.calls == 0, "an unsplittable node was expanded, at the cost of a feature pool"
    assert tree.root._is_leaf()


def test_a_node_with_exactly_two_leaves_worth_of_samples_is_still_expanded():
    """The boundary belongs on the permissive side: 64 samples can be cut 32/32."""
    X, y = _data(64)
    finder = CountingFinder()

    tree = _tree(finder, min_samples_leaf=32, max_depth=1)
    tree.fit(X, y, sequence_column=None)

    assert finder.calls == 1


def test_the_stopping_rule_agrees_with_the_split_validity_rule():
    """The two must not disagree: anything `_should_stop` lets through has to be splittable."""
    tree = _tree(CountingFinder(), min_samples_leaf=32)

    for n_pairs in range(1, 32):                          # 2 .. 62 samples
        assert tree._should_stop(np.array([0, 1] * n_pairs)), f"{2 * n_pairs} samples"

    assert not tree._should_stop(np.array([0, 1] * 32))    # 64 samples: 32/32 is a legal cut
